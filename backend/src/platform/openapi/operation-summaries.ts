// Adds each operation's summary to the generated document. Returns the ids
// that have no summary, so a test can fail on them.
export function applyOperationSummaries(document: OpenAPIObject): string[] {
  const missing: string[] = [];
  for (const operations of Object.values(document.paths))
    for (const operation of Object.values(operations as Record<string, { operationId?: string; summary?: string }>)) {
      if (!operation || typeof operation !== 'object' || !operation.operationId) continue;
      const summary = operationSummaries[operation.operationId];
      if (summary) operation.summary = summary;
      else missing.push(operation.operationId);
    }
  return missing;
}
